#!/usr/bin/env python3
"""Rewrite config/joint_limits.yaml from the joint limits of the robot description.
Run it after changing the arm:  python3 scripts/make_joint_limits.py [robot_model]
Needs the workspace built and sourced (xacro resolves $(find ...) through it)."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import xacro

CONFIG = Path(__file__).resolve().parent.parent / "config"
mappings = {"mode": "mock"}
if len(sys.argv) > 1:
    mappings["robot_model"] = sys.argv[1]
root = ET.fromstring(xacro.process_file(str(CONFIG / "gungnir.urdf.xacro"), mappings=mappings).toxml())

vel = {}
for joint in root.findall("joint"):
    lim = joint.find("limit")
    if joint.get("name") in ("J1", "J2", "J3", "J4", "J5", "J6") and lim is not None and lim.get("velocity"):
        vel[joint.get("name")] = float(lim.get("velocity"))
if len(vel) != 6:
    sys.exit(f"Expected 6 joints with velocity limits, found {sorted(vel)}")

out = ["# Generated by scripts/make_joint_limits.py from the robot description.",
       "# Velocity limits come from the URDF; acceleration limits are not set.",
       "default_velocity_scaling_factor: 0.1", "default_acceleration_scaling_factor: 0.1", "", "joint_limits:"]
for j in sorted(vel):
    out += [f"  {j}:", "    has_velocity_limits: true", f"    max_velocity: {vel[j]:.12g}",
            "    has_acceleration_limits: false", "    max_acceleration: 0"]
(CONFIG / "joint_limits.yaml").write_text("\n".join(out) + "\n")
print("wrote", CONFIG / "joint_limits.yaml")
for j in sorted(vel):
    print(f"  {j}: {vel[j]:.3f} rad/s ({vel[j] * 57.29578:.0f} deg/s)")
